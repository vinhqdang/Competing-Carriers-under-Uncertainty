"""Dual implementation pricing (DIP): the city's charges computed from the social optimum instead of a grid search.

Setting (ccu.zmc_brl.RoutingGame, D1).  Every lot of every carrier has vehicle-hours h = r * d (one ratio r for the
city), so the per-zone congestion charge t_z (per vehicle-hour) and a per-delivery charge act on the same variable:
a carrier pays u_z = s_z + r t_z per delivery in zone z.  The leader's instrument is the vector u (USD per delivery,
one number per zone).  Any u is realised by a uniform per-delivery charge s = min_z u_z (a subsidy when negative) plus
non-negative per-zone congestion charges t_z = (u_z - s) / r  (`instruments`).

With kappa_z = gc_z r^2 (carriers' congestion slope in delivery units), m_z = b_z + kappa_z and lots q_iz in {0, d_iz}:

    Phi_u(sigma) = SC(sigma) - sum_z kappa_z/2 (Q_z - Q*_z)^2 + sum_iz (m_z/2)(d_iz - dbar_z) q_iz + const      (*)

for the tangent charge u_z = kappa_z Q*_z - (m_z/2) dbar_z (theory/new_algorithm_C/theory.tex, Lemma 1).  Hence:

  1. target   : a pure social optimum sigma* (column generation on the social-cost potential + rounding + coordinate
                polish, the E3 machinery);  its zone aggregate Q* gives the tangent charge;
  2. implement: the set of flat charges u that make sigma* a pure Nash equilibrium is a polyhedron
                P(sigma*) = {u : <q_i(p) - q_i*, u> >= J_i^0(sigma*_i) - J_i^0(p)  for all i, p}.
                Its constraints are generated by the carriers' own routing oracle: one best response per carrier at
                sigma*_-i under the current u is an exact separation oracle.  An LP keeps u as close as possible
                (L1) to the tangent charge;
  3. if the polyhedron is empty (lumpy, asymmetric lots), the least-violating u is used and best-response dynamics
     from sigma* under u give the priced equilibrium; (*) bounds its loss.

The Gamma-maximin surcharge sur(delta) is linear in the contribution, so P_delta(sigma*) = P_0(sigma*) - sur(delta)
(`surcharge_shift`): implementing charges for every width are available without further oracle calls.
"""
from __future__ import annotations

import math
import time

import numpy as np
from scipy.optimize import linprog

from . import zmc

# ------------------------------------------------------------------------------------------------ structure


def lot_ratio(g) -> float:
    """r with h = r d for every lot of every carrier (collinearity of the two instruments within a zone)."""
    rs = np.concatenate([cr.h / cr.d for cr in g.carriers])
    r = float(np.median(rs))
    if not np.allclose(rs, r, rtol=1e-9, atol=1e-12):
        raise ValueError("vehicle-hours are not proportional to deliveries; DIP needs a common ratio h = r d")
    return r


def curvatures(g):
    """(kappa, m, mS): carriers' congestion slope, carriers' total slope, social slope (USD per delivery^2)."""
    r = lot_ratio(g)
    kappa = g.gc * r * r
    return kappa, g.b + kappa, g.b + 2.0 * kappa


def active_zones(g) -> np.ndarray:
    act = np.zeros(g.Z, bool)
    for cr in g.carriers:
        act[cr.zones] = True
    return act


def lots(g) -> np.ndarray:
    """D[i, z] = lot size of carrier i in zone z (0 when z is not one of its customer zones)."""
    D = np.zeros((g.N, g.Z))
    for i, cr in enumerate(g.carriers):
        D[i, cr.zones] = cr.d
    return D


def instruments(g, u) -> tuple[float, np.ndarray, np.ndarray]:
    """u (per-delivery equivalent, per zone) -> (s, t, toll): uniform per-delivery charge s, per-zone congestion
    charges t >= 0 (per vehicle-hour), and the 2Z toll vector of the game.  Exact: toll . a = u . q for every plan."""
    r = lot_ratio(g)
    act = active_zones(g)
    u = np.asarray(u, float)
    s = float(u[act].min()) if act.any() else 0.0
    t = np.where(act, (u - s) / r, 0.0)
    toll = np.concatenate([np.full(g.Z, s), t])
    return s, t, toll


def u_of_toll(g, toll) -> np.ndarray:
    """Per-delivery equivalent of a 2Z toll vector."""
    r = lot_ratio(g)
    return toll[: g.Z] + r * toll[g.Z:]


def social_cost(g, prof) -> float:
    return float(g.evaluate(prof)["social_cost"])


# ------------------------------------------------------------------------------------------------ step 1: target


def social_target(g, iters: int = 40):
    """Pure social optimum by column generation on the social-cost potential (convexified optimum), derandomised rounding
    and coordinate polish (same routine as E3).  Returns (target plans in the carriers' game, info)."""
    so = g.so_variant(False)
    so.toll = np.zeros(2 * g.Z)
    so.sur = np.zeros(2 * g.Z)
    c0 = so.calls
    cg = zmc.run_cg(so, iters=iters)
    relaxed = zmc.relaxed_value(so, cg["pools"], cg["weights"])
    # convexified aggregate (weights of the restricted master)
    Qbar = np.zeros(g.Z)
    for i in range(g.N):
        for w, p in zip(cg["weights"][i], cg["pools"][i]):
            Qbar += w * p.q
    target = [g.plan_from_routes(i, p.routes) for i, p in enumerate(cg["profile"])]
    info = dict(so_calls=so.calls - c0, so_relaxed=float(relaxed), so_pure=float(so.potential(cg["profile"])),
                Qbar=Qbar, cg_iters=len(cg["hist"]), so_game=so, pools=cg["pools"], weights=cg["weights"])
    return target, info


def tangent_charge(g, Q, target=None, ref: str = "mean") -> np.ndarray:
    """u_z = kappa_z Q_z - (m_z/2) dbar_z.  dbar_z is the mean lot of the carriers with a customer in z ('mean'), or of the
    carriers serving z in the target ('served', falls back to 'mean')."""
    kappa, m, _ = curvatures(g)
    D = lots(g)
    has = D > 0
    dbar = np.where(has.any(0), D.sum(0) / np.maximum(has.sum(0), 1), 0.0)
    if ref == "served" and target is not None:
        S = np.array([p.q for p in target]) > 0
        ds = np.where(S.any(0), (D * S).sum(0) / np.maximum(S.sum(0), 1), dbar)
        dbar = ds
    u = kappa * Q - 0.5 * m * dbar
    return np.where(active_zones(g), u, 0.0)


def personalised_charge(g, target) -> np.ndarray:
    """U[i, z] = kappa_z Q*_{-i,z} - (b_z/2) d_iz: per-carrier rates under which every coordinatewise minimum of the social
    cost is an exact pure equilibrium (Proposition 2).  Reported for comparison; a city cannot charge per carrier."""
    kappa, m, mS = curvatures(g)
    D = lots(g)
    Q = sum(p.q for p in target)
    return np.array([kappa * (Q - p.q) - 0.5 * g.b * D[i] for i, p in enumerate(target)])


# ------------------------------------------------------------------------------------------------ step 2: implement


def _set_u(g, u, sur=None):
    _, _, toll = instruments(g, u)
    g.set_charges(toll=toll, sur=sur if sur is not None else g.sur)


def _lp(B, ufix, ref, cuts, lo, hi, pen=1e4):
    """min ||y - ref||_1 + pen * sum(slack)  s.t.  G y + slack >= h (cuts), lo <= ufix + B y <= hi.

    cuts: list of (dq, rhs) meaning <dq, ufix + B y> >= rhs.  Returns (y, total slack)."""
    k = B.shape[1]
    nc = len(cuts)
    # variables: y (k), e+ (k), e- (k), slack (nc)   with y = ref + e+ - e-
    nv = 3 * k + nc
    c = np.concatenate([np.zeros(k), np.ones(k), np.ones(k), pen * np.ones(nc)])
    Aeq = np.zeros((k, nv))
    Aeq[:, :k] = np.eye(k)
    Aeq[:, k:2 * k] = -np.eye(k)
    Aeq[:, 2 * k:3 * k] = np.eye(k)
    beq = np.asarray(ref, float)
    rows, rhs = [], []
    for j, (dq, r0) in enumerate(cuts):
        row = np.zeros(nv)
        row[:k] = -(dq @ B)
        row[3 * k + j] = -1.0
        rows.append(row)
        rhs.append(-(r0 - float(dq @ ufix)))
    # box on u = ufix + B y
    for z in range(B.shape[0]):
        if not np.any(B[z]):
            continue
        row = np.zeros(nv)
        row[:k] = B[z]
        rows.append(row.copy())
        rhs.append(hi[z] - ufix[z])
        rows.append(-row)
        rhs.append(-(lo[z] - ufix[z]))
    bounds = [(None, None)] * k + [(0, None)] * (2 * k + nc)
    res = linprog(c, A_ub=np.array(rows) if rows else None, b_ub=np.array(rhs) if rhs else None, A_eq=Aeq, b_eq=beq,
                  bounds=bounds, method="highs")
    if res.status != 0:
        raise RuntimeError("DIP LP failed: " + res.message)
    y = res.x[:k]
    slack = float(res.x[3 * k:].sum()) if nc else 0.0
    return y, slack


def implement(g, target, u_ref, basis=None, ufix=None, max_rounds: int = 12, margin: float = 1e-4, tol: float = 1e-7,
              log=None):
    """Cutting-plane search for a charge u in P(target) closest (L1) to u_ref, restricted to u = ufix + B y.

    Separation oracle: one best response per carrier at target_-i under the current u (N routing calls per round).
    Returns dict(u, status in {'exact', 'empty', 'rounds'}, rounds, cuts, slack, regret_max)."""
    Z = g.Z
    act = active_zones(g)
    if basis is None:
        idx = np.flatnonzero(act)
        B = np.zeros((Z, len(idx)))
        B[idx, np.arange(len(idx))] = 1.0
        ufix = np.zeros(Z)
        yref = u_ref[idx].copy()
    else:
        B = np.asarray(basis, float)
        ufix = np.zeros(Z) if ufix is None else np.asarray(ufix, float)
        yref = np.linalg.lstsq(B[act], (u_ref - ufix)[act], rcond=None)[0]
    lo = np.where(act, -g.alpha, 0.0)
    hi = np.where(act, g.alpha, 0.0)
    A = sum(p.a for p in target)
    y = yref.copy()
    cuts, seen = [], set()
    status, slack, rounds, regmax = "rounds", 0.0, 0, np.inf
    for rnd in range(max_rounds):
        rounds = rnd + 1
        u = ufix + B @ y
        _set_u(g, u)
        regs = np.zeros(g.N)
        new = 0
        for i, p in enumerate(target):
            Am = A - p.a
            pt = g.plan_from_routes(i, p.routes)  # re-priced under the current charges
            b = g.br(i, Am)
            gain = g.J(i, pt, Am) - g.J(i, b, Am)
            regs[i] = max(gain, 0.0)
            if gain > tol:
                key = (i, b.key())
                if key not in seen:
                    seen.add(key)
                    # <q_b - q*_i, u> >= J0(target_i) - J0(b) + margin, J0 = J - u.q
                    j0t = g.J(i, pt, Am) - float(u @ pt.q)
                    j0b = g.J(i, b, Am) - float(u @ b.q)
                    cuts.append((b.q - pt.q, j0t - j0b + margin))
                    new += 1
        regmax = float(regs.max())
        if log is not None:
            log.append(dict(round=rounds, regret_max=regmax, n_cuts=len(cuts), calls=g.calls))
        if regmax <= tol:
            status = "exact"
            break
        if new == 0:  # violated deviations already cut: the LP had to use slack
            status = "empty"
            break
        y, slack = _lp(B, ufix, yref, cuts, lo, hi)
        if slack > 1e-9:
            status = "empty"
            u = ufix + B @ y
            break
    u = ufix + B @ y
    _set_u(g, u)
    return dict(u=u, status=status, rounds=rounds, n_cuts=len(cuts), slack=slack, regret_max=regmax, cuts=cuts)


# ------------------------------------------------------------------------------------------------ driver


def potential_wedge(g, prof, Qstar, u_tan) -> float:
    """Right-hand side of (*) without SC: -sum kappa/2 (Q - Q*)^2 + sum (m/2)(d_iz - dbar_z) q_iz (dbar implied by u_tan)."""
    kappa, m, _ = curvatures(g)
    act = active_zones(g)
    dbar = np.where(act, 2.0 * (kappa * Qstar - u_tan) / np.where(act, m, 1.0), 0.0)
    Q = sum(p.q for p in prof)
    D = lots(g)
    L = sum(float(((0.5 * m) * (D[i] - dbar) * p.q).sum()) for i, p in enumerate(prof))
    return float(-0.5 * (kappa * (Q - Qstar) ** 2).sum() + L)


def _implement_target(g, target, family=None, max_rounds=12, polish=True, log=None) -> dict:
    """Steps 2-3 for one target: tangent charge, cutting plane, fallback.  Calls are counted on g."""
    c0 = g.calls
    Qstar = sum(p.q for p in target)
    u_tan = tangent_charge(g, Qstar)
    if family is None:
        imp = implement(g, target, u_tan, max_rounds=max_rounds, log=log)
    else:
        B, ufix = family
        imp = implement(g, target, u_tan, basis=B, ufix=ufix, max_rounds=max_rounds, log=log)
    u, prof, br_ok = fallback(g, target, imp, u_tan, family) if (imp["status"] != "exact" and polish) else \
        (imp["u"], None, True)
    _set_u(g, u)
    if prof is None:
        prof = [g.plan_from_routes(i, p.routes) for i, p in enumerate(target)]
    s, t, toll = instruments(g, u)
    out = dict(profile=prof, u=u, u_tan=u_tan, s=s, t=t, toll=toll, status=imp["status"], rounds=imp["rounds"],
               n_cuts=imp["n_cuts"], slack=imp["slack"], converged=bool(br_ok), target=target, Qstar=Qstar,
               sc_target=social_cost(g, target), sc=social_cost(g, prof), calls_implement=g.calls - c0)
    # a posteriori loss bound (Theorem 9): SC(prof) - SC(target) <= wedge(target) - wedge(prof) + <u - u_tan, Q* - Q>
    Q = sum(p.q for p in prof)
    out["loss_vs_target"] = out["sc"] - out["sc_target"]
    out["loss_bound"] = 0.0 if imp["status"] == "exact" else float(
        potential_wedge(g, target, Qstar, u_tan) - potential_wedge(g, prof, Qstar, u_tan) + (u - u_tan) @ (Qstar - Q))
    return out


def improve_target(g, target, info, restarts: int = 3, seed: int = 0):
    """Multi-start coordinate polish of the social cost: from the empty profile and from `restarts - 1` profiles sampled
    from the column-generation weights.  Returns (best target, calls spent)."""
    so = info["so_game"]
    c0 = so.calls
    rng = np.random.default_rng(seed)
    P, W = info["pools"], info["weights"]
    starts = [[so.empty_plan(i) for i in range(g.N)]]
    for _ in range(max(restarts - 1, 0)):
        st = []
        for i in range(g.N):
            w = np.maximum(np.array(W[i], float), 0.0)
            st.append(P[i][int(rng.choice(len(P[i]), p=w / w.sum()))] if w.sum() > 0 else P[i][0])
        starts.append(st)
    best = [so.plan_from_routes(i, p.routes) for i, p in enumerate(target)]
    bv = so.potential(best)
    for st in starts:
        st = [so.plan_from_routes(i, p.routes) for i, p in enumerate(st)]
        pr, _ = zmc.br_dynamics(so, init=st)
        v = so.potential(pr)
        if v < bv - 1e-9:
            best, bv = pr, v
    return [g.plan_from_routes(i, p.routes) for i, p in enumerate(best)], so.calls - c0


def dip(g, so_iters: int = 40, target=None, target_info=None, max_rounds: int = 12, family=None, polish: bool = True,
        restarts: int = 3, log=None) -> dict:
    """Full method.  family=None: zone charges (u free per zone); family=(B, ufix): u restricted to ufix + B y
    (e.g. the grid's two-parameter family).  restarts > 0: after implementing the column-generation target, a multi-start
    polish of the social cost looks for a better target, which is implemented too; the better priced equilibrium is
    returned.  The result of the first target alone is kept under the key 'first'."""
    t0 = time.perf_counter()
    st0 = dict(g._st)
    c0 = g.calls
    if target is None:
        target, target_info = social_target(g, iters=so_iters)
    so_calls = (target_info or {}).get("so_calls", 0)
    first = _implement_target(g, target, family, max_rounds, polish, log)
    first["calls"] = so_calls + first["calls_implement"]
    first["time_s"] = time.perf_counter() - t0
    out = dict(first)
    ms_calls = 0
    if restarts and target_info and "pools" in target_info:
        tgt2, ms_calls = improve_target(g, target, target_info, restarts=restarts)
        if social_cost(g, tgt2) < first["sc_target"] - 1e-9:
            second = _implement_target(g, tgt2, family, max_rounds, polish, log)
            if second["sc"] < first["sc"] - 1e-9:
                out = dict(second)
                out["calls_implement"] = first["calls_implement"] + second["calls_implement"]
            else:
                out["calls_implement"] = first["calls_implement"] + second["calls_implement"]
    _set_u(g, out["u"])
    out.update(first=first, calls_so=so_calls + ms_calls, calls_restarts=ms_calls,
               calls=so_calls + ms_calls + g.calls - c0, time_s=time.perf_counter() - t0)
    out["calls_implement"] = g.calls - c0
    out["bp_calls"] = g._st["calls"] - st0["calls"]
    if target_info:
        out.update(so_relaxed=target_info.get("so_relaxed"), so_pure=target_info.get("so_pure"))
    return out


def fallback(g, target, imp, u_ref, family=None):
    """Target not implementable by flat charges: best-response dynamics from the target under two candidate charges, the
    least-violating LP charge and the reference charge (tangent, or its least-squares projection on the family); the
    candidate whose equilibrium has the lower social cost is kept.  Returns (u, profile, converged)."""
    cands = [imp["u"]]
    if family is None:
        cands.append(np.where(active_zones(g), u_ref, 0.0))
    else:
        B, ufix = family
        act = active_zones(g)
        y = np.linalg.lstsq(B[act], (u_ref - ufix)[act], rcond=None)[0]
        cands.append(ufix + B @ y)
    best = None
    for u in cands:
        _set_u(g, u)
        prof = [g.plan_from_routes(i, p.routes) for i, p in enumerate(target)]
        prof, ok = zmc.br_dynamics(g, init=prof)
        sc = social_cost(g, prof)
        if best is None or sc < best[0] - 1e-9:
            best = (sc, u, prof, ok)
    return best[1], best[2], best[3]


def surcharge_shift(g, u, sur) -> np.ndarray:
    """Implementing charge under the Gamma-maximin surcharge sur (2Z vector): u(delta) = u(0) - (sur_q + r sur_tau)."""
    return np.asarray(u, float) - u_of_toll(g, np.asarray(sur, float))


def grid_family(g, ext) -> tuple[np.ndarray, np.ndarray]:
    """Basis of the grid's family u_z = s + r theta ext_z  (ext = gc X^NE per vehicle-hour): y = (s, theta)."""
    r = lot_ratio(g)
    act = active_zones(g)
    B = np.stack([act.astype(float), np.where(act, r * ext, 0.0)], 1)
    return B, np.zeros(g.Z)
